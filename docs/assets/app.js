  function setActiveNav(id) {
    document.querySelectorAll(".nav-link, .nav-child").forEach((n) => n.classList.remove("active"));
    const target = document.querySelector(`[data-id="${CSS.escape(id)}"]`);
    if (target) {
      target.classList.add("active");
      const group = target.closest(".nav-group");
      if (group) group.classList.add("open");
      target.scrollIntoView({ block: "nearest" });
    }
  }

  /* ---------- Router ---------- */
  function route() {
    const hash = location.hash.replace(/^#\/?/, "");
    const id = decodeURIComponent(hash) || "home";
    state.currentId = id;
    window.scrollTo({ top: 0 });
    if (id === "home") renderHome();
    else if (state.docsById[id]) renderDoc(id);
    else renderNotFound(id);
    setActiveNav(id === "home" ? "home" : id);
    closeSidebar();
  }

  /* ---------- Markdown rendering ---------- */
  function configureMarked() {
    marked.setOptions({ gfm: true, breaks: false, headerIds: false, mangle: false });
  }

  function renderMarkdown(md) {
    const html = marked.parse(md);
    const wrap = el("div");
    wrap.innerHTML = html;
    // rewrite internal repo links to hash routes; open external in new tab
    wrap.querySelectorAll("a[href]").forEach((a) => {
      const href = a.getAttribute("href");
      if (/^https?:\/\//i.test(href)) { a.target = "_blank"; a.rel = "noopener"; return; }
      if (href.startsWith("#")) return;
      const mapped = mapRepoLink(href);
      if (mapped) a.setAttribute("href", mapped);
    });
    // headings: ids + anchors, collect for TOC
    const toc = [];
    wrap.querySelectorAll("h1, h2, h3").forEach((h) => {
      const id = slug(h.textContent);
      h.id = id;
      if (h.tagName !== "H1") {
        toc.push({ id, text: h.textContent, level: h.tagName === "H2" ? 2 : 3 });
        h.insertAdjacentHTML("beforeend", ` <a class="head-anchor" href="#/${state.currentId}#${id}" aria-label="Link">#</a>`);
      }
    });
    // code blocks: highlight + wrap with copy button
    wrap.querySelectorAll("pre > code").forEach((code) => {
      try { hljs.highlightElement(code); } catch (_) {}
      const pre = code.parentElement;
      const block = el("div", "code-block");
      pre.replaceWith(block);
      block.appendChild(pre);
      const btn = el("button", "copy-btn", copyLabel());
      btn.addEventListener("click", () => copyCode(btn, code.textContent));
      block.appendChild(btn);
    });
    // make tables scrollable already handled by CSS
    return { node: wrap, toc };
  }

  function mapRepoLink(href) {
    let h = href.replace(/^\.\//, "").replace(/[?#].*$/, "");
    h = h.replace(/\/$/, "").replace(/\/README\.md$/i, "").replace(/\.md$/i, "");
    if (!h) return null;
    const map = {
      "README": "home", "ROADMAP": "roadmap", "CHEATSHEET": "cheatsheet",
      "INTERVIEW": "interview", "PATTERNS": "patterns", "GLOSSARY": "glossary",
      "PYTHON_TO_AI_ENGINEERING": "python-to-ai", "AGENTS": null, "CLAUDE": null,
    };
    if (h in map) return map[h] ? "#/" + map[h] : null;
    if (state.docsById[h]) return "#/" + h;
    return null;
  }

  const copyLabel = () => `<svg viewBox="0 0 24 24" class="icon" style="width:13px;height:13px"><rect x="9" y="9" width="11" height="11" rx="2"/><path d="M5 15V5a2 2 0 0 1 2-2h10"/></svg>Copy`;
  function copyCode(btn, text) {
    navigator.clipboard.writeText(text).then(() => {
      btn.classList.add("copied");
      btn.innerHTML = `✓ Copied`;
      setTimeout(() => { btn.classList.remove("copied"); btn.innerHTML = copyLabel(); }, 1600);
    });
  }

  /* ---------- Doc page ---------- */
  function renderDoc(id) {
    const doc = state.docsById[id];
    markVisited(id);
    localStorage.setItem(LS_LAST, id);

    const content = $("#content");
    content.innerHTML = "";

    // header/meta for modules
    const head = el("div", "doc-head");
    if (doc.kind === "module" || doc.status || doc.level) {
      const badges = el("div", "doc-badges");
      if (doc.status) badges.innerHTML += `<span class="badge status-${doc.status}">${doc.status === "Written" ? "✅" : "🚧"} ${doc.status}</span>`;
      if (doc.level) badges.innerHTML += `<span class="badge level">Level: ${esc(doc.level)}</span>`;
      if (doc.source) badges.innerHTML += `<a class="badge" href="${state.data.meta.repo_url}/blob/main/${doc.source}" target="_blank" rel="noopener">Source ↗</a>`;
      if (badges.children.length) head.appendChild(badges);
    }
    content.appendChild(head);

    const { node, toc } = renderMarkdown(doc.markdown);
    content.appendChild(node);

    // embedded example code
    if (doc.code && doc.code.length) {
      const sec = el("section", "code-files");
      sec.appendChild(el("h2", null, `Example code <span style="font-size:13px;color:var(--text-faint);font-weight:400">(${doc.code.length} file${doc.code.length > 1 ? "s" : ""})</span>`));
      sec.firstChild.id = "example-code";
      toc.push({ id: "example-code", text: "Example code", level: 2 });
      doc.code.forEach((f) => sec.appendChild(codeFileItem(f)));
      content.appendChild(sec);
    }

    renderCrumbs(id, doc);
    renderPager(id, doc);
    renderToc(toc);
    setupScrollSpy();
    handleInPageAnchor();
  }

  function codeFileItem(f) {
    const item = el("div", "cf-item");
    const head = el("div", "cf-head");
    head.innerHTML = `${svg("chev", "chev")}<span>${esc(f.name)}</span><span class="cf-lang">${esc(f.language)}</span>`;
    const body = el("div", "cf-body");
    const pre = el("pre");
    const code = el("code", `language-${f.language}`);
    code.textContent = f.code;
    pre.appendChild(code);
    const block = el("div", "code-block");
    block.appendChild(pre);
    const btn = el("button", "copy-btn", copyLabel());
    btn.addEventListener("click", (e) => { e.stopPropagation(); copyCode(btn, f.code); });
    block.appendChild(btn);
    body.appendChild(block);
    head.addEventListener("click", () => {
      const open = item.classList.toggle("open");
      if (open && !code.dataset.hl) { try { hljs.highlightElement(code); } catch (_) {} code.dataset.hl = "1"; }
    });
    item.appendChild(head);
    item.appendChild(body);
    return item;
  }

  function renderCrumbs(id, doc) {
    const parts = [`<a href="#/home">Home</a>`];
    const group = findGroupFor(id);
    if (group) parts.push(`<span class="sep">/</span><span>${esc(group.title)}</span>`);
    parts.push(`<span class="sep">/</span><span>${esc(doc.title)}</span>`);
    $("#crumbs").innerHTML = parts.join(" ");
  }

  function findGroupFor(id) {
    for (const item of state.data.nav) {
      if (item.type === "group" && item.children.some((c) => c.id === id)) return item;
    }
    return null;
  }

  function renderPager(id, doc) {
    const pager = $("#pager");
    pager.innerHTML = "";
    let prevId = doc.prev, nextId = doc.next;
    if (prevId === undefined || nextId === undefined) {
      // fall back to flat nav order for non-module docs
      const idx = state.navFlat.findIndex((n) => n.id === id);
      if (idx !== -1) {
        prevId = prevId ?? (idx > 0 ? state.navFlat[idx - 1].id : null);
        nextId = nextId ?? (idx < state.navFlat.length - 1 ? state.navFlat[idx + 1].id : null);
      }
    }
    if (prevId && state.docsById[prevId]) {
      const a = el("a", "prev");
      a.href = "#/" + prevId;
      a.innerHTML = `<span class="pg-label">← Previous</span><span class="pg-title">${esc(state.docsById[prevId].title)}</span>`;
      pager.appendChild(a);
    } else pager.appendChild(el("span"));
    if (nextId && state.docsById[nextId]) {
      const a = el("a", "next");
      a.href = "#/" + nextId;
      a.innerHTML = `<span class="pg-label">Next →</span><span class="pg-title">${esc(state.docsById[nextId].title)}</span>`;
      pager.appendChild(a);
    }
  }

  function renderToc(toc) {
    const box = $("#toc");
    if (!toc.length) { box.innerHTML = ""; return; }
    box.innerHTML = `<div class="toc-title">On this page</div>`;
    toc.forEach((t) => {
      const a = el("a", t.level === 3 ? "h3" : "");
      a.href = `#/${state.currentId}#${t.id}`;
      a.dataset.target = t.id;
      a.textContent = t.text.replace(/\s*#$/, "");
      a.addEventListener("click", (e) => { e.preventDefault(); scrollToHeading(t.id); });
      box.appendChild(a);
    });
  }

  function scrollToHeading(hid) {
    const h = document.getElementById(hid);
    if (h) {
      h.scrollIntoView({ behavior: "smooth", block: "start" });
      history.replaceState(null, "", `#/${state.currentId}#${hid}`);
    }
  }

  function handleInPageAnchor() {
    const m = location.hash.match(/#\/[^#]*#(.+)$/);
    if (m) setTimeout(() => scrollToHeading(m[1]), 60);
  }

  let spy;
  function setupScrollSpy() {
    if (spy) spy.disconnect();
    const links = [...document.querySelectorAll("#toc a")];
    if (!links.length) return;
    const map = new Map(links.map((a) => [a.dataset.target, a]));
    spy = new IntersectionObserver((entries) => {
      entries.forEach((en) => {
        if (en.isIntersecting) {
          links.forEach((a) => a.classList.remove("active"));
          const a = map.get(en.target.id);
          if (a) a.classList.add("active");
        }
      });
    }, { rootMargin: "-70px 0px -70% 0px", threshold: 0 });
    document.querySelectorAll(".content h2, .content h3").forEach((h) => spy.observe(h));
  }

